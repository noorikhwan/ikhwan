function generateInitialRacks(): RackDefinition[] {
  const list: RackDefinition[] = [];
  for (let hIdx = 0; hIdx < HALL_CONFIGS.length; hIdx++) {
    const hall = HALL_CONFIGS[hIdx];
    for (let rowNum = 1; rowNum <= ROWS_PER_HALL; rowNum++) {
      const rowStr = String(rowNum).padStart(2, '0');
      for (let rackNum = 1; rackNum <= RACKS_PER_ROW; rackNum++) {
        const rackStr = String(rackNum).padStart(2, '0');
        const id = `${hall.code}-R${rowStr}-${rackStr}`;
        // Deterministic spatial load/thermal distribution (warmer near center of rows/halls)
        const centerFactor = 1 - Math.abs(rackNum - 10.5) / 14;
        const rowWave = Math.sin((rowNum * 0.65 + rackNum * 0.4 + hIdx * 1.9)) * 0.12;
        const loadRatio = Math.max(
          0.22,
          Math.min(0.86, hall.baseLoadRatio + centerFactor * 0.14 + rowWave)
        );
        // Two high-density AI training cabinets in Hall B run an active burst over rated 22 kW capacity
        const basePowerKw =
          id === 'B-R03-10'
            ? 22.85
            : id === 'B-R12-11'
            ? 22.45
            : Number((hall.powerCapacityKw * loadRatio).toFixed(2));
        const basePeakTempC = Number(
          Math.max(
            35.0,
            Math.min(73.5, hall.baseTempC + centerFactor * 5.2 + rowWave * 18)
          ).toFixed(1)
        );
        const baseUsedU = Math.min(40, Math.max(18, Math.round(24 + loadRatio * 18)));
        list.push({
          id,
          name: `Rack ${hall.code}${rowStr}-${rackStr}`,
          hallId: hall.id,
          hallName: hall.label,
          row: `Row ${rowStr} · ${hall.aisleStyle}`,
          rowNumber: rowNum,
          rackIndex: rackNum,
          totalU: 42,
          powerCapacityKw: hall.powerCapacityKw,
          manufacturer: assignRackManufacturer(hall.id, rackNum),
          powerDensityRating: deriveRackPowerDensityRating(hall.powerCapacityKw),
          ambientTempC: Number((hall.ambientTempC + (rowNum % 3) * 0.2).toFixed(1)),
          basePowerKw,
          basePeakTempC,
          baseUsedU,
          pduAName: `PDU-${hall.code}${rowStr}-A`,
          pduBName: `PDU-${hall.code}${rowStr}-B`,
        });
      }
    }
  }
  return list;
}

