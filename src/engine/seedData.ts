function buildServerHistory(
  baseCpu: number,
  baseMem: number,
  baseTemp: number,
  basePower: number,
  baseNet: number,
  seedOffset: number,
  now: number
): ServerSample[] {
  const points: ServerSample[] = [];
  for (let i = 19; i >= 0; i--) {
    const wave = Math.sin((i + seedOffset) * 0.55) * 3.2 + Math.cos((i + seedOffset) * 0.25) * 1.8;
    points.push({
      timestamp: now - i * 3000,
      cpu: Number(Math.max(4, Math.min(99, baseCpu + wave)).toFixed(1)),
      memory: Number(Math.max(10, Math.min(99, baseMem + wave * 0.45)).toFixed(1)),
      tempC: Number(Math.max(28, Math.min(94, baseTemp + wave * 0.4)).toFixed(1)),
      powerW: Math.round(Math.max(120, basePower + wave * 12)),
      networkGbps: Number(Math.max(0.5, baseNet + wave * 0.4).toFixed(1)),
    });
  }
  return points;
}

