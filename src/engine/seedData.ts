export const BASE_CAMPUS_RACK_LOAD_KW = Number(
  INITIAL_RACKS.reduce((acc, r) => acc + r.basePowerKw, 0).toFixed(1)
);

export function createInitialFacilityHistory(servers: ServerNode[], now = Date.now()): FacilityTelemetryPoint[] {
  const monitoredKw = servers.reduce((acc, s) => acc + s.powerW, 0) / 1000;
  const basePowerKw = Number((BASE_CAMPUS_RACK_LOAD_KW + monitoredKw * 12).toFixed(1));
  const baseCpu = servers.reduce((acc, s) => acc + s.cpu, 0) / servers.length;
  const baseTemp = servers.reduce((acc, s) => acc + s.tempC, 0) / servers.length;
  const baseNet = servers.reduce((acc, s) => acc + s.networkGbps, 0);

  const points: FacilityTelemetryPoint[] = [];
  for (let i = 23; i >= 0; i--) {
    const ts = now - i * 3000;
    const wave = i === 0 ? 0 : Math.sin(i * 0.45) * 0.6 + Math.cos(i * 0.2) * 0.35;
    const kw = Number((basePowerKw + wave * 125).toFixed(1));
    const d = new Date(ts);
    const label = `${String(d.getHours()).padStart(2, '0')}:${String(d.getMinutes()).padStart(2, '0')}:${String(d.getSeconds()).padStart(2, '0')}`;
    const temp = Number((baseTemp + wave * 0.7).toFixed(1));
    points.push({
      timestamp: ts,
      label,
      totalPowerKw: kw,
      pue: Number((1.22 + Math.max(0, (temp - 45) * 0.008)).toFixed(2)),
      avgCpu: Number((baseCpu + wave * 2.4).toFixed(1)),
      avgTempC: temp,
      totalNetworkGbps: Number((baseNet + wave * 14).toFixed(1)),
    });
  }
  return points;
}
