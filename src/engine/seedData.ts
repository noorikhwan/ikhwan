export function deriveRackPowerDensityRating(powerCapacityKw: number): RackPowerDensityRating {
  if (powerCapacityKw >= 20) return 'High-Density (22 kW)';
  if (powerCapacityKw >= 14) return 'Medium (14–16 kW)';
  return 'Standard (12 kW)';
}

function assignRackManufacturer(hallId: HallMeta['id'], rackNum: number): RackManufacturer {
  const isOdd = rackNum % 2 === 1;
  switch (hallId) {
    case 'hall-a':
      return isOdd ? 'Schneider Electric' : 'Rittal';
    case 'hall-b':
      return isOdd ? 'Vertiv' : 'Schneider Electric';
    case 'hall-c':
      return isOdd ? 'Rittal' : 'Panduit';
    case 'hall-d':
      return isOdd ? 'Panduit' : 'Vertiv';
  }
}

